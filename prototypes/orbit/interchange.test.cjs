'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {validate,midiFile}=require('./session.js');
const fixture=validate(JSON.parse(fs.readFileSync(path.join(__dirname,'../../Tests/fixtures/orbit-shared.json'))));
assert.equal(fixture.phrase.length,12);assert(fixture.phrase[1].rest);
if(!process.argv[2])throw new Error('Pass the JSON generated by the native Orbit test');
const native=validate(JSON.parse(fs.readFileSync(process.argv[2])));
assert.equal(native.phrase.length,12);assert.equal(native.phrase[0].beats,2);assert(native.phrase[1].rest);
assert.equal(native.scenes.filter(Boolean).length,2);assert.equal(native.scenes[0].controls.tone,20);assert.equal(native.scenes[1].controls.tone,80);
assert.equal(native.controls.swing,40);assert(midiFile(native).length>100);
console.log('PASS: native → web preset, full rhythm, scene bank, controls and MIDI export');

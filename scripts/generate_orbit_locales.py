"""Generate both UI catalogs from locales/orbit.json; --check detects stale outputs."""
import argparse
import json
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
catalog = json.loads((root / 'locales/orbit.json').read_text())
languages = list(catalog['languages'])
assert languages[0] == 'it' and 'en' in languages
for source, translations in catalog['messages'].items():
    assert set(translations) == set(languages) - {'it'}, source
    for language, translated in translations.items():
        assert translated and set(re.findall(r'\{\w+\}', source)) == set(re.findall(r'\{\w+\}', translated)), (source, language)

js = '/* Generated by scripts/generate_orbit_locales.py. Do not edit. */\n'
js += '(function(root){const catalog=' + json.dumps(catalog, ensure_ascii=False, separators=(',', ':'))
js += ';if(typeof module!=="undefined")module.exports=catalog;else root.OrbitTranslations=catalog;})(globalThis);\n'
quote = lambda s: json.dumps(s, ensure_ascii=False)
header = '// Generated by scripts/generate_orbit_locales.py. Do not edit.\n#pragma once\nnamespace orbit::localization {\n'
header += 'inline constexpr const char* languageIds[]={' + ','.join(map(quote, languages)) + '};\n'
header += 'inline constexpr const char* languageNames[]={' + ','.join(quote(catalog['languages'][k]) for k in languages) + '};\n'
header += f'struct Entry {{const char* source;const char* values[{len(languages)}];}};\ninline constexpr Entry messages[]={{\n'
for source, translations in catalog['messages'].items():
    header += '    {' + quote(source) + ',{' + ','.join(quote(source if k == 'it' else translations[k]) for k in languages) + '}},\n'
header += '};\n}\n'
for relative, content in [('prototypes/orbit/translations.js', js), ('Source/Orbit/Translations.h', header)]:
    path = root / relative
    if args.check:
        assert path.exists() and path.read_text() == content, f'Stale catalog: {relative}'
    else:
        path.write_text(content)
print(f'{"Verified" if args.check else "Generated"} {len(languages)} languages, {len(catalog["messages"])} messages for web and native')
